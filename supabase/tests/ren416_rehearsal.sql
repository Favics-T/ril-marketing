    WHERE qual ILIKE '%caller_organization_ids%' OR with_check ILIKE '%caller_organization_ids%';
  IF n <> 48 THEN
    RAISE EXCEPTION 'FAIL 6: % policies use caller_organization_ids(), expected 48 unchanged', n;
  END IF;
END $$;

