// Builds supabase/tests/ren416_rehearsal.sql from the REN-416 migration and
// isolation checks, so the rehearsal always runs exactly what will ship.
//   node scripts/build-ren416-rehearsal.mjs           write the file
//   node scripts/build-ren416-rehearsal.mjs --check   exit 1 if it is stale
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const MIGRATION = "supabase/migrations/20261015000000_workspace_access_fix.sql";
const CHECKS = "supabase/tests/ren416_workspace_isolation.sql";
const OUTPUT = "supabase/tests/ren416_rehearsal.sql";
const read = (path) => readFileSync(root + path, "utf8").replace(/\r\n/g, "\n");

const migration = read(MIGRATION).trimEnd();
if (/^\s*(BEGIN|COMMIT|END|ROLLBACK)\s*;/im.test(migration)) {
  throw new Error(`${MIGRATION} controls its own transaction; the rehearsal can't wrap it safely.`);
}
const checks = read(CHECKS);
const start = checks.indexOf("\nBEGIN;\n");
const end = checks.lastIndexOf("\nROLLBACK;");
if (start < 0 || end < start) throw new Error(`${CHECKS} must be wrapped in BEGIN; … ROLLBACK;`);
const body = checks.slice(start + "\nBEGIN;\n".length, end).trim();

const rule = "-- ======================================================================";
const rehearsal = `-- REN-416 rehearsal: apply the migration and run every isolation check in
-- ONE transaction, then roll it all back. Safe to run on production: nothing
-- is committed, whether the run passes or fails.
--
-- How to run: paste the whole file into the Supabase SQL editor and run it
-- once, at a quiet time. The migration takes short exclusive locks on
-- profiles, organization_members and organizations, so app requests touching
-- those tables wait until the run ends (normally a second or two).
-- Pass: no error; the last result reads "REN-416 isolation checks passed".
-- Fail: the run stops at an error starting "FAIL" (or another error). COMMIT
-- is never reached, so every change, including the migration, is discarded.
--
-- Generated by scripts/build-ren416-rehearsal.mjs: the BEGIN below is
-- followed by the migration verbatim, then the body of
-- ren416_workspace_isolation.sql verbatim, then ROLLBACK. Don't edit this
-- file; change those two and run the script. The migration has no
-- BEGIN/COMMIT of its own (the Supabase CLI wraps each migration in a
-- transaction), so nothing inside can end this transaction early.

BEGIN;

${rule}
-- MIGRATION: ${MIGRATION}
${rule}

${migration}

${rule}
-- CHECKS: body of ${CHECKS}
${rule}

${body}

ROLLBACK;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = read(OUTPUT); } catch { /* missing counts as stale */ }
  if (current !== rehearsal) {
    console.error(`${OUTPUT} is out of date. Run: node scripts/build-ren416-rehearsal.mjs`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date.`);
} else {
  writeFileSync(root + OUTPUT, rehearsal);
  console.log(`Wrote ${OUTPUT}.`);
}
